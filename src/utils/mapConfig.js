const cfgRef = (key) => refs.mapConfig(key)

// Shared helper: merge Firestore data with per-key registry defaults so every
// field is always defined regardless of which Firestore doc fields exist.
function withRegistryDefaults(key, data) {
  const base = DEFAULT_MAP_CONFIGS[key] ?? { tilesets: {}, collision: {}, hidden: {} }
  return {
    // A generated, non-editable map owns its tileset list: stored configs from before a
    // redraw must not hide the new tileset (the registry entries always win).
    tilesets:     base.editable === false
      ? { ...(data.tilesets ?? {}), ...base.tilesets }
      : data.tilesets ?? base.tilesets ?? {},
    collision:    data.collision    ?? base.collision ?? {},
    hidden:       data.hidden       ?? base.hidden    ?? {},
    displayName:  data.displayName  ?? base.displayName ?? key,
    order:        data.order        ?? 0,
    isEntry:      data.isEntry      ?? base.isEntry ?? false,
    defaultSpawn: data.defaultSpawn ?? base.defaultSpawn ?? null,
    multiplayer:  data.multiplayer  ?? base.multiplayer ?? false,
    critters:     data.critters     ?? base.critters ?? false,
    editable:     data.editable     ?? base.editable ?? false,
    // What a generated map IS is decided by the registry alone (a stored document cannot turn the
    // study room off or make another map a campus). The scene reads these to draw furniture / buildings.
    room:         base.room   ?? false,
    campus:       base.campus ?? false,
  }
}

// Returns the stored config for a map, or its built-in default. Falls back to the
// default on any read error so the game still boots offline / before first save.
export async function getMapConfig(key) {
  const fallback = withRegistryDefaults(key, {})
  try {
    const snap = await getDoc(cfgRef(key))
    if (!snap.exists()) return fallback
    return withRegistryDefaults(key, snap.data())
  } catch {
    return fallback
  }
}

export async function saveMapConfig(key, cfg, uid) {
  if (!uid) console.warn('[saveMapConfig] no uid passed — updatedBy will be null (audit trail lost)')
  const { tilesets, collision, hidden, displayName, order, isEntry, defaultSpawn, multiplayer, editable } = cfg
  // Strip undefined values so callers that omit new registry fields don't write
  // `undefined` to Firestore (the modular SDK throws on undefined field values).
  const payload = Object.fromEntries(
    Object.entries({
      tilesets, collision, hidden,
      displayName, order, isEntry, defaultSpawn, multiplayer, editable,
      updatedAt: serverTimestamp(), updatedBy: uid ?? null,
    }).filter(([, v]) => v !== undefined),
  )
  await setDoc(cfgRef(key), payload, { merge: true })
}

// List every map in the registry, sorted by order then key.
export async function listMapConfigs() {
  const snap = await getDocs(cols.mapConfigs)
  const maps = snap.docs.map((d) => ({ key: d.id, ...withRegistryDefaults(d.id, d.data()) }))
  maps.sort((a, b) => (a.order ?? 0) - (b.order ?? 0) || a.key.localeCompare(b.key))
  return maps
}

// Maps removed by the Study Room (ADR-0023): a stored document or a remembered key for one of
// these must never decide where the app boots.
const RETIRED_MAP_KEYS = ['test3', 'test2']

// Pure: the map to boot into, never a retired one; the room when nothing else qualifies.
// Built-in maps count even before an admin has saved a document for them.
export function resolveEntryKey(maps) {
  const stored = (maps ?? []).filter((m) => !RETIRED_MAP_KEYS.includes(m.key))
  const builtIns = Object.keys(DEFAULT_MAP_CONFIGS)
    .filter((key) => !RETIRED_MAP_KEYS.includes(key) && !stored.some((m) => m.key === key))
    .map((key) => ({ key, ...withRegistryDefaults(key, {}) }))
  return pickEntryKey([...stored, ...builtIns]) ?? 'room'
}

// Pure: may the app boot straight into this map? It must exist (stored or built in), must not
// be retired, and must not be the School Hub (that needs its async room choice: enterSchoolHub).
export function isResumableMapKey(key, maps) {
  if (typeof key !== 'string' || RETIRED_MAP_KEYS.includes(key) || key === 'school_hub') return false
  return (maps ?? []).some((m) => m.key === key) || key in DEFAULT_MAP_CONFIGS
}

// Pure: where to boot given the stored resume points. Falls back to the normal entry map at
// its default spawn whenever the remembered map or point cannot be used.
export function resolveBootTarget(maps, resume) {
  const fallbackKey = resolveEntryKey(maps)
  return pickBootTarget({ resume, isAllowed: (k) => isResumableMapKey(k, maps), fallbackKey })
}

// Pure: choose which map loads on boot.
export function pickEntryKey(maps) {
  if (!maps || maps.length === 0) return null
  const flagged = maps.find((m) => m.isEntry === true)
  if (flagged) return flagged.key
  return [...maps].sort((a, b) => (a.order ?? 0) - (b.order ?? 0))[0].key
}
